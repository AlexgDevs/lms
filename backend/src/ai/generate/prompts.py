"""Prompts for the two-phase course generation pipeline.

All prompts are in Russian to generate Russian-language course content."""


def modules_prompt(course_topic: str, modules_count: int) -> str:
    return (
        f'Ты — методист, создающий структуру онлайн-курса на тему "{course_topic}".\n\n'
        f"Сгенерируй ровно {modules_count} модулей (разделов) этого курса.\n"
        f"Каждый модуль должен охватывать отдельную, самостоятельную область темы.\n"
        f"Порядок: от базовых концепций к продвинутым.\n\n"
        f"Требования:\n"
        f"- Названия должны быть конкретными и описательными (не «Раздел 1»)\n"
        f"- Описания должны объяснять, что изучается в модуле, 1-2 предложениями\n"
        f"- Названия до 150 символов, описания до 500 символов\n"
        f"- Весь текст на русском языке\n\n"
        f"Верни строго валидный JSON:\n"
        f'{{"modules": [{{"title": "...", "description": "..."}}]}}'
    )


def lessons_prompt(
    course_topic: str,
    module_title: str,
    module_description: str,
    lessons_count: int,
) -> str:
    return (
        f"Ты — методист, создающий уроки для модуля онлайн-курса.\n"
        f'Курс: "{course_topic}"\n'
        f'Модуль: "{module_title}" — {module_description}\n\n'
        f"Сгенерируй ровно {lessons_count} уроков для этого модуля.\n"
        f"Уроки должны.progressively: от простого к сложному внутри модуля.\n\n"
        f"Требования:\n"
        f"- Каждый урок должен охватывать одну конкретную подтему\n"
        f"- Названия должны быть конкретными (не «Урок 1»)\n"
        f"- Описания должны объяснять, чему учит урок, 1 предложением\n"
        f"- Названия до 150 символов, описания до 500 символов\n"
        f"- Весь текст на русском языке\n\n"
        f"Верни строго валидный JSON:\n"
        f'{{"lessons": [{{"title": "...", "description": "..."}}]}}'
    )


def batch_lesson_plans_prompt(
    course_topic: str,
    module_title: str,
    lessons: list[dict[str, str]],
    blocks_per_lesson: int,
) -> str:
    lessons_list = "\n".join(
        f'  {i + 1}. "{les["title"]}" — {les.get("description", "")}'
        for i, les in enumerate(lessons)
    )
    return (
        f"Ты — методист, создающий подробный план уроков.\n"
        f'Курс: "{course_topic}"\n'
        f'Модуль: "{module_title}"\n\n'
        f"Список уроков:\n{lessons_list}\n\n"
        f"Для КАЖДОГО урока определи тип и спланируй ровно {blocks_per_lesson} блоков.\n\n"
        f"Типы уроков:\n"
        f'- "theory" — теоретическое объяснение (текст + тест)\n'
        f'- "practice" — практический навык (текст + тест)\n'
        f'- "assessment" — проверка знаний (преимущественно тест)\n'
        f'- "theory_with_practice" — объяснение + применение (текст + тест)\n\n'
        f"Доступные типы блоков:\n"
        f"- text — информационный контент, объяснения, определения, примеры\n"
        f"- quiz_single_choice — тест с одним правильным ответом\n"
        f"- quiz_multiple_choice — тест с несколькими правильными ответами\n"
        f"- code — программирование (ТОЛЬКО для тем, связанных с программированием/математикой)\n"
        f"- image — иллюстрация или диаграмма\n\n"
        f"Правила планирования блоков:\n"
        f"1. ВСЕГДА начинай с 1-2 текстовых блоков, объясняющих ключевые концепции\n"
        f"2. ЗАКАНЧИВАЙ 1-2 тестовыми блоками для проверки понимания\n"
        f"- Кодовые блоки ТОЛЬКО если тема связана с программированием\n"
        f"- Каждый блок должен иметь ЧЁТКОЕ назначение (1 предложение)\n"
        f"- Текстовые блоки должны логически вытекать друг из друга\n"
        f"- Тестовые вопросы должны проверять знания из текстовых блоков\n\n"
        f"Верни строго валидный JSON:\n"
        f'{{"plans": [{{"lesson_title": "...", "lesson_type": "...", "blocks": [{{"type": "...", "purpose": "..."}}]}}]}}'
    )


def batch_blocks_content_prompt(
    course_topic: str,
    module_title: str,
    lesson_title: str,
    lesson_type: str,
    blocks: list[dict[str, str]],
) -> str:
    blocks_list = "\n".join(
        f'  {i + 1}. Тип: {b["type"]}, Назначение: {b["purpose"]}'
        for i, b in enumerate(blocks)
    )
    total = len(blocks)
    return (
        f"Ты — эксперт-педагог, создающий учебный контент.\n"
        f'Курс: "{course_topic}"\n'
        f'Модуль: "{module_title}"\n'
        f'Урок: "{lesson_title}"\n'
        f"Тип урока: {lesson_type}\n\n"
        f"Список блоков для генерации:\n{blocks_list}\n\n"
        f"Сгенерируй ПОЛНЫЙ контент для КАЖДОГО блока.\n\n"
        f"═══════════════════════════════════════════════════\n"
        f"ПРАВИЛА ДЛЯ ТЕКСТОВЫХ БЛОКОВ (type: text):\n"
        f"═══════════════════════════════════════════════════\n"
        f"- ОБЯЗАН содержать минимум 3 абзаца по 3-5 предложений каждый\n"
        f"- Каждый абзац должен содержать конкретную информацию: факты, цифры, определения\n"
        f"- Используй структуру: определение → объяснение → примеры → практика\n"
        f"- Никогда не пиши «В этом уроке мы изучим...» или «Содержание...»\n"
        f"- Пиши конкретно: что это, как работает, зачем нужно, примеры применения\n"
        f"- Весь текст на русском языке\n"
        f"- MINIMUM 300 символов в текстовом блоке\n\n"
        f"Пример ХОРОШЕГО текстового блока:\n"
        f'"payload": {{"text": "Гель для ногтей — это полимерный материал, который наносится '
        f"на натуральный ноготь и затвердевает под воздействием УФ-лампы. Основное преимущество "
        f"геля перед обычным лаком — его прочность: покрытие держится 2-3 недели без сколов. "
        f"Существует два типа геля:rowsers (самовыравнивающийся) и builder (нужно формировать). "
        f"Для начинающих мастеров рекомендуется использовать soak-off гель, который легко снимается "
        f'специальным раствором."}}\n\n'
        f"═══════════════════════════════════════════════════\n"
        f"ПРАВИЛА ДЛЯ ТЕСТОВЫХ БЛОКОВ (quiz_single_choice / quiz_multiple_choice):\n"
        f"═══════════════════════════════════════════════════\n"
        f"- Ровно 4 варианта ответа\n"
        f"- Вопрос должен проверять знания из ПРЕДЫДУЩИХ текстовых блоков\n"
        f"- 1 правильный ответ для quiz_single_choice, 2-3 для quiz_multiple_choice\n"
        f"- Остальные варианты — правдоподобные, но неверные (распространённые ошибки)\n"
        f"- Весь текст на русском языке\n\n"
        f"═══════════════════════════════════════════════════\n"
        f"ПРАВИЛА ДЛЯ КОДОВЫХ БЛОКОВ (code):\n"
        f"═══════════════════════════════════════════════════\n"
        f"- Полный рабочий пример кода с комментариями\n"
        f"- 2-3 тест-кейса с вводом/выводом\n"
        f"- Python (если тема не требует другой язык)\n\n"
        f"═══════════════════════════════════════════════════\n"
        f"ПРАВИЛА ДЛЯ ИЗОБРАЖЕНИЙ (image):\n"
        f"═══════════════════════════════════════════════════\n"
        f"- Подробное описание того, что должно быть на изображении\n\n"
        f"Верни строго валидный JSON:\n"
        f'{{"blocks": [{{"block_index": 1, "title": "Название блока", "payload": {{"text": "..."}}}}]}}'
    )


def single_block_content_prompt(
    course_topic: str,
    module_title: str,
    lesson_title: str,
    lesson_type: str,
    block_type: str,
    block_purpose: str,
    block_index: int,
    blocks_total: int,
    previous_blocks_summary: str,
) -> str:
    position_hint = ""
    if block_index == 0:
        position_hint = "Это ПЕРВЫЙ блок — представь тему чётко и понятно."
    elif block_index == blocks_total - 1:
        position_hint = "Это ПОСЛЕДНИЙ блок — подведи итог."
    else:
        position_hint = (
            f"Это блок {block_index + 1} из {blocks_total} — "
            f"продолжай развивать предыдущий контент."
        )

    rules = _get_block_rules(block_type)

    return (
        f"Ты — эксперт-педагог, создающий учебный контент.\n"
        f'Курс: "{course_topic}"\n'
        f'Модуль: "{module_title}"\n'
        f'Урок: "{lesson_title}"\n'
        f"Тип урока: {lesson_type}\n\n"
        f"Блок {block_index + 1} из {blocks_total}\n"
        f"Тип блока: {block_type}\n"
        f"Назначение блока: {block_purpose}\n"
        f"{position_hint}\n\n"
        f"Предыдущие блоки в этом уроке:\n{previous_blocks_summary}\n\n"
        f"{rules}\n\n"
        f"ВАЖНО: Пиши подробный, содержательный контент. "
        f"Никогда не пиши «Содержание» или «В этом уроке мы изучим...». "
        f"Давай конкретные определения, примеры, цифры, факты.\n\n"
        f"Верни строго валидный JSON:\n"
        f'{{"title": "Название блока", "payload": {{<схема для типа блока>}}}}'
    )


def _get_block_rules(block_type: str) -> str:
    rules = {
        "text": (
            "═══════════════════════════════════════════════════\n"
            "ПРАВИЛА ДЛЯ ТЕКСТОВОГО БЛОКА:\n"
            "═══════════════════════════════════════════════════\n"
            "- ОБЯЗАН содержать минимум 3 абзаца по 3-5 предложений\n"
            "- Каждый абзац: конкретная информация (факт, определение, пример)\n"
            "- Структура: определение → объяснение → примеры → практика\n"
            "- MINIMUM 300 символов\n"
            "- Никогда не пиши «Содержание» или подобные шаблоны\n"
            "- Весь текст на русском языке\n\n"
            'Пример: "payload": {{"text": "Гель для ногтей — это полимерный материал... (3+ абзаца реального контента)"}}'
        ),
        "quiz_single_choice": (
            "═══════════════════════════════════════════════════\n"
            "ПРАВИЛА ДЛЯ ТЕСТА С ОДНИМ ОТВЕТОМ:\n"
            "═══════════════════════════════════════════════════\n"
            "- Ровно 4 варианта ответа\n"
            "- Вопрос проверяет знания из предыдущих текстовых блоков\n"
            "- 1 правильный ответ\n"
            "- Остальные — правдоподобные ошибки\n"
            "- Весь текст на русском языке\n\n"
            'Формат: {{"options": [{{"id": 0, "text": "..."}}, ...], "correct_option_id": 0}}'
        ),
        "quiz_multiple_choice": (
            "═══════════════════════════════════════════════════\n"
            "ПРАВИЛА ДЛЯ ТЕСТА С НЕСКОЛЬКИМИ ОТВЕТАМИ:\n"
            "═══════════════════════════════════════════════════\n"
            "- Ровно 4 варианта ответа\n"
            "- Вопрос проверяет знания из предыдущих текстовых блоков\n"
            "- 2-3 правильных ответа\n"
            "- Остальные — правдоподобные ошибки\n"
            "- Весь текст на русском языке\n\n"
            'Формат: {{"options": [{{"id": 0, "text": "..."}}, ...], "correct_option_ids": [0, 2]}}'
        ),
        "code": (
            "═══════════════════════════════════════════════════\n"
            "ПРАВИЛА ДЛЯ КОДОВОГО БЛОКА:\n"
            "═══════════════════════════════════════════════════\n"
            "- Полный рабочий пример с комментариями\n"
            "- 2-3 тест-кейса с вводом/выводом\n"
            "- Python (если тема не требует другой язык)\n\n"
            'Формат: {{"code": "...", "language": "python", "test_cases": [{{"input": "...", "output": "..."}}]}}'
        ),
        "image": (
            "═══════════════════════════════════════════════════\n"
            "ПРАВИЛА ДЛЯ ИЗОБРАЖЕНИЯ:\n"
            "═══════════════════════════════════════════════════\n"
            "- Подробное описание того, что должно быть на изображении\n"
            "- Описание должно быть достаточно детальным для художника\n\n"
            'Формат: {{"alt_text": "Описание изображения"}}'
        ),
    }
    return rules.get(block_type, rules["text"])
